#[cfg(test)]
mod tests {
    use super::{REGISTRY, WSTICKET_INTERNAL_NOTE};
    use crate::client::Operation;
    use std::collections::BTreeSet;

    #[test]
    fn registry_covers_53_public_reads_plus_internal_note() {
        assert_eq!(REGISTRY.len(), 53);
        let mut keys = BTreeSet::new();
        let mut operations = BTreeSet::new();
        for entry in REGISTRY {
            assert!(keys.insert(entry.key), "duplicate key {}", entry.key);
            assert!(
                operations.insert(format!("{:?}", entry.operation)),
                "duplicate operation {:?}",
                entry.operation
            );
            assert_eq!(entry.method, "GET");
            assert!(!entry.path.is_empty());
        }
        assert!(WSTICKET_INTERNAL_NOTE.contains("ws-ticket"));
        assert!(!operations.contains(&format!("{:?}", Operation::WsTicket)));
    }
}
